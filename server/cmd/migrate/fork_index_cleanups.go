// mergeForkIndexCleanups runs during package variable initialization, not in init():
// preMigrationHooks (main.go) is built from concurrentIndexCleanups in its own variable
// initializer, which runs before any init(). Go starts the earliest-declared variable
// that is ready, and the compiler sees files in name order, so this file's variable runs
// right after concurrentIndexCleanups and before preMigrationHooks.
// TestConcurrentIndexCleanupsMatchTheirMigrations fails if that ordering ever breaks.
var _ = mergeForkIndexCleanups()

func mergeForkIndexCleanups() struct{} {
	for version, index := range forkConcurrentIndexCleanups {
		if _, taken := concurrentIndexCleanups[version]; taken {
			panic(fmt.Sprintf("migration %s is registered in both concurrentIndexCleanups and forkConcurrentIndexCleanups", version))
		}
		concurrentIndexCleanups[version] = index
	}
	return struct{}{}
}
