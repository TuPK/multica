// Builders for skill content: the quickstart bundle (TypeScript) and the starter skills (Go).
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { frontmatterDescription, skillFiles } from "../../lib/skill-bundle.mjs";

// The files an installed skill carries: everything beside SKILL.md except the catalog's own
// manifest and translations.
function installedFiles(dir) {
  return skillFiles(dir)
    .filter((file) => file !== "template.json" && !file.startsWith("i18n/"))
    .sort()
    .map((file) => ({ path: file, content: readFileSync(resolve(dir, file), "utf8") }));
}

// Skills of the sets whose target is `target`, sorted by folder name (as the old generator did).
export function skillsOfTarget(entries, target) {
  const setTarget = new Map(entries.filter((e) => e.kind === "skillset").map((e) => [e.manifest.id, e.manifest.target]));
  return entries
    .filter((e) => e.kind === "skill" && (e.manifest.sets ?? []).some((set) => setTarget.get(set) === target))
    .sort((a, b) => (a.folder < b.folder ? -1 : a.folder > b.folder ? 1 : 0));
}

export function bundleSkill(entry) {
  const content = readFileSync(resolve(entry.dir, "SKILL.md"), "utf8");
  const description = frontmatterDescription(content, entry.folder);
  if (!description) throw new Error(`${entry.folder}/SKILL.md has an empty description`);
  return { name: entry.manifest.id, description, content, files: installedFiles(entry.dir) };
}

// The members of every skillset, by skill id, in folder-name order (the order the old SDLC bundle used).
export function skillsetMembers(entries) {
  const out = {};
  for (const set of entries.filter((e) => e.kind === "skillset")) out[set.manifest.id] = [];
  const skills = entries.filter((e) => e.kind === "skill").sort((a, b) => (a.folder < b.folder ? -1 : a.folder > b.folder ? 1 : 0));
  for (const skill of skills) {
    for (const set of skill.manifest.sets ?? []) out[set]?.push(skill.manifest.id);
  }
  return out;
}

export function renderSkillsBuiltin(entries) {
  const skills = skillsOfTarget(entries, "quickstart").map(bundleSkill);
  return `// Generated by scripts/catalog/cli.mjs from catalog/skills. Not committed: run \`pnpm catalog:build\`.

export interface BuiltinSkillFile {
  path: string;
  content: string;
}

export interface BuiltinSkill {
  name: string;
  description: string;
  content: string;
  files: BuiltinSkillFile[];
}

/** The built-in skills the squad quickstart imports: every skill of a skillset whose target is "quickstart". */
export const SDLC_BUILTIN_SKILLS: readonly BuiltinSkill[] = ${JSON.stringify(skills, null, 2)};
`;
}

// The skillset membership is its own small file, so code that only needs a squad's skill names does
// not pull in the bundle above (about 2 MB of skill text).
export function renderSkillsets(entries) {
  return `// Generated by scripts/catalog/cli.mjs from catalog/skills. Not committed: run \`pnpm catalog:build\`.

/** The skill ids of each skillset (in folder-name order), from the \`sets\` of the skills' template.json. */
export const SKILLSET_MEMBERS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(skillsetMembers(entries), null, 2)};
`;
}

// The starter skills as the Go apply service reads them (the shape of company_template_data.json).
export function starterSkillsForGo(entries) {
  return skillsOfTarget(entries, "starter").map((entry) => {
    const content = readFileSync(resolve(entry.dir, "SKILL.md"), "utf8");
    const description = /^description: "(.*)"$/m.exec(content)?.[1];
    if (!description) throw new Error(`${entry.folder}/SKILL.md has no description in its frontmatter`);
    const files = installedFiles(entry.dir).filter((file) => file.path.endsWith(".md") && !file.path.includes("/"));
    return { name: entry.manifest.id, description, content, files };
  });
}
