// Squads, collections and their translations as TypeScript data. The assembly of a SquadTemplate from
// this data (and from the Kit Viet pack) is hand-written code in packages/core/catalog/squads.ts.
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const byOrder = (a, b) => (a.manifest.order ?? 1e9) - (b.manifest.order ?? 1e9) || (a.manifest.id < b.manifest.id ? -1 : 1);
const union = (values) => (values.length ? values.map((v) => JSON.stringify(v)).join(" | ") : "never");
const HEADER = "// Generated by scripts/catalog/cli.mjs from catalog/. Not committed: run `pnpm catalog:build`.\n";

export function renderCollections(entries) {
  const collections = entries.filter((e) => e.kind === "collection").sort(byOrder).map((e) => ({ id: e.manifest.id }));
  return `${HEADER}
export type SquadTemplateCategory = ${union(collections.map((c) => c.id))};

/** The groups of the squad quickstart, in the order they are listed. */
export const CATALOG_COLLECTIONS: readonly { id: SquadTemplateCategory }[] = ${JSON.stringify(collections, null, 2)};
`;
}

export function squadRecords(entries) {
  const collectionOrder = new Map(entries.filter((e) => e.kind === "collection").sort(byOrder).map((e, i) => [e.manifest.id, i]));
  return entries
    .filter((e) => e.kind === "squad")
    .sort((a, b) => collectionOrder.get(a.manifest.collection) - collectionOrder.get(b.manifest.collection) || byOrder(a, b))
    .map((e) => {
      const { manifest } = e;
      const squad = { ...manifest.squad };
      const instructionsPath = join(e.dir, "instructions.md");
      if (existsSync(instructionsPath)) squad.instructions = readFileSync(instructionsPath, "utf8");
      return {
        id: manifest.id,
        version: manifest.version,
        status: manifest.status ?? "stable",
        collection: manifest.collection,
        ...(manifest.expertReview === undefined ? {} : { expertReview: manifest.expertReview }),
        ...(manifest.adapter === undefined ? {} : { adapter: manifest.adapter }),
        squad,
      };
    });
}

export function renderSquads(entries) {
  const records = squadRecords(entries);
  const roleKeys = [...new Set(records.flatMap((r) => r.squad.roles.map((role) => role.key)))];
  return `${HEADER}import type { CatalogSquad } from "../types";

export type SquadTemplateId = ${union(records.map((r) => r.id))};

/** Every role key of every squad. A role several squads share is listed once. */
export type SquadRoleKey = ${union(roleKeys)};

export const CATALOG_SQUADS: readonly CatalogSquad[] = ${JSON.stringify(records, null, 2)};
`;
}

// The instructions the agent of each role starts from (catalog/squads/<id>/roles/<role key>.md), by squad.
export function roleInstructionsBySquad(entries) {
  const out = {};
  for (const e of entries.filter((x) => x.kind === "squad")) {
    const dir = join(e.dir, "roles");
    if (!existsSync(dir)) continue;
    out[e.manifest.id] = Object.fromEntries(
      readdirSync(dir).filter((f) => f.endsWith(".md")).sort().map((f) => [f.replace(/\.md$/, ""), readFileSync(join(dir, f), "utf8")]),
    );
  }
  return out;
}

export function renderRoleInstructions(entries) {
  return `${HEADER}
/** The agent instructions of the roles that write their own (catalog/squads/<id>/roles), by squad id and role key. */
export const CATALOG_ROLE_INSTRUCTIONS_BY_SQUAD: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(roleInstructionsBySquad(entries), null, 2)};
`;
}

// The translations of every template with UI text: "<kind>:<id>" -> locale -> text.
export function renderI18n(entries, locales) {
  const out = {};
  for (const e of entries) {
    const dir = join(e.dir, "i18n");
    if (!existsSync(dir)) continue;
    out[`${e.kind}:${e.manifest.id}`] = Object.fromEntries(locales.map((locale) => [locale, JSON.parse(readFileSync(join(dir, `${locale}.json`), "utf8"))]));
  }
  return `${HEADER}
export const CATALOG_I18N: Readonly<Record<string, Readonly<Record<string, { title: string; description?: string }>>>> = ${JSON.stringify(out, null, 2)};
`;
}
