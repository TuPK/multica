// The starter company and the agent instruction templates: TypeScript data for the web and desktop
// apps, and one JSON file for the Go apply service (the shape company_template_data.go reads).
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { starterSkillsForGo } from "./build-skills.mjs";

const HEADER = "// Generated by scripts/catalog/cli.mjs from catalog/. Not committed: run `pnpm catalog:build`.\n";
const union = (values) => (values.length ? values.map((v) => JSON.stringify(v)).join(" | ") : "never");

export function blocksOf(catalogRoot) {
  const dir = join(catalogRoot, "agents", "_blocks");
  const blocks = {};
  if (!existsSync(dir)) return blocks;
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".md")).sort()) {
    blocks[file.replace(/\.md$/, "")] = readFileSync(join(dir, file), "utf8");
  }
  return blocks;
}

const expandBlocks = (text, blocks, where) =>
  text.replace(/\{\{block:([a-z_]+)\}\}/g, (_, name) => {
    if (!(name in blocks)) throw new Error(`${where}: unknown block {{block:${name}}}`);
    return blocks[name];
  });

// The agent instruction templates in listed order, with their blocks expanded.
export function agentInstructions(entries, catalogRoot) {
  const blocks = blocksOf(catalogRoot);
  return entries
    .filter((e) => e.kind === "agent")
    .sort((a, b) => (a.manifest.order ?? 1e9) - (b.manifest.order ?? 1e9) || (a.manifest.id < b.manifest.id ? -1 : 1))
    .map((e) => ({
      id: e.manifest.id,
      instructions: expandBlocks(readFileSync(join(e.dir, "instructions.md"), "utf8"), blocks, `agents/${e.manifest.id}/instructions.md`),
    }));
}

export function renderAgents(entries, catalogRoot) {
  const templates = agentInstructions(entries, catalogRoot);
  const blocks = blocksOf(catalogRoot);
  return `${HEADER}
export type AgentInstructionTemplateId = ${union(templates.map((t) => t.id))};

/** The agent instruction templates in listed order (catalog/agents), with their shared blocks expanded. */
export const CATALOG_AGENT_INSTRUCTIONS: readonly { id: AgentInstructionTemplateId; instructions: string }[] = ${JSON.stringify(templates, null, 2)};

/** The text blocks the templates share (catalog/agents/_blocks), by name. */
export const CATALOG_AGENT_BLOCKS = ${JSON.stringify(blocks, null, 2)} as const;
`;
}

function company(entries) {
  const entry = entries.find((e) => e.kind === "company" && e.manifest.id === "starter");
  if (!entry) throw new Error("catalog/companies/starter is missing");
  return entry.manifest.company;
}

export function renderCompany(entries) {
  const c = company(entries);
  return `${HEADER}
export const COMPANY_FLOOR_KEYS = ${JSON.stringify(c.floorKeys)} as const;

export const COMPANY_FLOOR_NAMES = ${JSON.stringify(c.floorNames, null, 2)} as const;

export const COMPANY_SQUAD_KEYS = ${JSON.stringify(c.squadKeys)} as const;

export const COMPANY_STAGE_KEYS = ${JSON.stringify(c.stageKeys)} as const;

export const COMPANY_STAGE_OWNERS_DATA = ${JSON.stringify(c.stageOwners, null, 2)} as const;

export const COMPANY_START_OPTIONS = ${JSON.stringify(c.startOptions)} as const;

/** The squad cards as written in catalog/companies/starter; company-template.ts checks them against its schema. */
export const COMPANY_SQUAD_CARDS_DATA: readonly unknown[] = ${JSON.stringify(c.squads, null, 2)};
`;
}

// The file the Go apply service embeds: the same data as the TypeScript side, plus the starter skills.
export function companyForGo(entries, catalogRoot) {
  const c = company(entries);
  return {
    generated_by: "scripts/catalog/cli.mjs",
    floor_keys: c.floorKeys,
    floor_names: c.floorNames,
    start_options: c.startOptions,
    squads: c.squads,
    stage_owners: c.stageOwners,
    instruction_templates: agentInstructions(entries, catalogRoot),
    starter_skills: starterSkillsForGo(entries),
  };
}

export function validateCompany(entry, problems, context) {
  const { manifest, path } = entry;
  const err = (message) => problems.errors.push(`${path}: ${message}`);
  const c = manifest.company;
  if (!c || typeof c !== "object") return err("company block is missing");
  for (const field of ["floorKeys", "squadKeys", "stageKeys", "startOptions", "stageOwners", "squads"]) {
    if (!Array.isArray(c[field])) err(`company.${field} must be an array`);
  }
  if (problems.errors.some((e) => e.startsWith(path))) return;
  const squadKeys = c.squads.map((s) => s.key);
  if (JSON.stringify(squadKeys) !== JSON.stringify(c.squadKeys)) err("company.squadKeys must list the squads' keys in order");
  if (JSON.stringify(c.stageOwners.map((s) => s.key)) !== JSON.stringify(c.stageKeys)) err("company.stageKeys must list the stage owners' keys in order");
  for (const floor of c.floorKeys) if (!c.floorNames?.[floor]) err(`company.floorNames has no name for floor ${floor}`);
  for (const squad of c.squads) {
    if (!c.floorKeys.includes(squad.floor)) err(`squad ${squad.key} sits on unknown floor ${squad.floor}`);
    for (const role of squad.roles ?? []) {
      if (!context.ids.has(`agent:${role.agentTemplate}`)) err(`squad ${squad.key} role ${role.key} uses unknown agent template ${role.agentTemplate}`);
    }
  }
  for (const owner of c.stageOwners) if (!squadKeys.includes(owner.owner)) err(`stage ${owner.key} is owned by unknown squad ${owner.owner}`);
}

export function validateAgent(entry, problems, context) {
  const { dir, path } = entry;
  const err = (message) => problems.errors.push(`${path}: ${message}`);
  const file = join(dir, "instructions.md");
  if (!existsSync(file)) return err("instructions.md is missing");
  const text = readFileSync(file, "utf8");
  if (text.trim() === "") err("instructions.md is empty");
  for (const [, name] of text.matchAll(/\{\{block:([a-z_]+)\}\}/g)) {
    if (!context.blocks[name]) err(`instructions.md uses unknown block {{block:${name}}}`);
  }
}
