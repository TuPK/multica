// Agent packs: catalog/packs/<id>/ becomes one JSON bundle the web and desktop apps install from.
// (scripts/install-agent-pack.sh reads the same directories directly.)
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { basename, join, relative } from "node:path";

function listFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

function readText(path, root) {
  const buffer = readFileSync(path);
  if (buffer.includes(0)) throw new Error(`${relative(root, path)} looks binary; packs carry text only`);
  return buffer.toString("utf8");
}

export function buildPackBundle(packDir, root) {
  const id = basename(packDir);
  const manifest = JSON.parse(readText(join(packDir, "pack.json"), root));
  const { agent } = manifest;
  return {
    id,
    agent: {
      name: agent.name,
      description: agent.description,
      instructions: readText(join(packDir, agent.instructions_file), root),
      max_concurrent_tasks: agent.max_concurrent_tasks,
    },
    skills: manifest.skills.map((name) => {
      const skillDir = join(packDir, "skills", name);
      return {
        name,
        files: listFiles(skillDir)
          .map((file) => ({ path: relative(skillDir, file).split("\\").join("/"), content: readText(file, root) }))
          .sort((a, b) => a.path.localeCompare(b.path)),
      };
    }),
  };
}

const HEADER = "// Generated by scripts/catalog/cli.mjs from catalog/packs. Not committed: run `pnpm catalog:build`.\n";

// The ids of the agent packs and the loader of each bundle, so a new pack needs no code change.
export function renderPackIndex(ids) {
  const sorted = [...ids].sort();
  return `${HEADER}
export const AGENT_PACK_IDS = ${JSON.stringify(sorted)} as const;
export type AgentPackId = (typeof AGENT_PACK_IDS)[number];

/** One loader per pack bundle, so a bundle is fetched only when its pack is installed. */
export const AGENT_PACK_LOADERS: Record<AgentPackId, () => Promise<{ default: unknown }>> = {
${sorted.map((id) => `  ${JSON.stringify(id)}: () => import(${JSON.stringify(`./${id}.json`)}),`).join("\n")}
};
`;
}

export function validatePack(entry, problems) {
  const err = (message) => problems.errors.push(`${entry.path}: ${message}`);
  let manifest;
  try {
    manifest = JSON.parse(readFileSync(join(entry.dir, "pack.json"), "utf8"));
  } catch (e) {
    return err(`pack.json is missing or not valid JSON (${e.message})`);
  }
  const agent = manifest.agent;
  if (!agent || typeof agent.name !== "string" || typeof agent.instructions_file !== "string") return err("pack.json needs agent.name and agent.instructions_file");
  if (!existsSync(join(entry.dir, agent.instructions_file))) err(`${agent.instructions_file} is missing`);
  if (!Array.isArray(manifest.skills) || manifest.skills.length === 0) err("pack.json must list skills");
  for (const name of manifest.skills ?? []) {
    if (!/^[a-z0-9][a-z0-9._-]*$/.test(name)) err(`skill name ${name} is not valid`);
    if (!existsSync(join(entry.dir, "skills", name, "SKILL.md"))) err(`skills/${name}/SKILL.md is missing`);
  }
}

export function packDirs(catalogRoot) {
  const dir = join(catalogRoot, "packs");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .map((name) => join(dir, name))
    .filter((path) => existsSync(join(path, "pack.json")));
}
