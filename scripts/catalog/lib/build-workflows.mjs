// Workflow templates: TypeScript data for the quickstart and one JSON file for the Go build workflow.
import { createHash } from "node:crypto";
import { isNonEmptyString, isObject } from "./validate-shared.mjs";

const HEADER = "// Generated by scripts/catalog/cli.mjs from catalog/. Not committed: run `pnpm catalog:build`.\n";

// An executable workflow has a `workflow` block; a designer template has a `designer` block instead;
// a flow template has a `flow` block (the squad's enforced flow).
export const isExecutableWorkflow = (entry) => entry.kind === "workflow" && entry.manifest.workflow !== undefined;
export const isDesignerWorkflow = (entry) => entry.kind === "workflow" && entry.manifest.designer !== undefined;
export const isFlowWorkflow = (entry) => entry.kind === "workflow" && entry.manifest.flow !== undefined;

export function workflowsById(entries) {
  return Object.fromEntries(
    entries.filter(isExecutableWorkflow).sort((a, b) => (a.manifest.id < b.manifest.id ? -1 : 1)).map((e) => [e.manifest.id, e.manifest.workflow]),
  );
}

export function renderWorkflows(entries) {
  return `${HEADER}import type { CatalogWorkflow } from "../types";

/** The workflow templates (catalog/workflows), by id. */
export const CATALOG_WORKFLOWS: Readonly<Record<string, CatalogWorkflow>> = ${JSON.stringify(workflowsById(entries), null, 2)};
`;
}

// The system templates of the workflow designer, in board order of the picker (the manifests' `order`).
// Each is the shape server/internal/issueworkflow reads: a step is an existing status (statusKey) or one
// the save creates (new); a transition without `on` is the default branch.
export function designerTemplates(entries) {
  return entries
    .filter(isDesignerWorkflow)
    .sort((a, b) => (a.manifest.order ?? 0) - (b.manifest.order ?? 0) || (a.manifest.id < b.manifest.id ? -1 : 1))
    .map((e) => ({ id: e.manifest.designer.templateId, steps: e.manifest.designer.steps }));
}

// A status key from a status name, as issuestatus.DeriveKey does for the names these workflows use.
export const deriveKey = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "");

// ---- Flow templates (spec 8: the `flow` block of catalog/workflows/flow_<squad id>) ----

// JSON with the keys of every object in sorted order, so equal content gives equal text.
function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  if (isObject(value)) return `{${Object.keys(value).sort().filter((k) => value[k] !== undefined).map((k) => `${JSON.stringify(k)}:${canonicalJson(value[k])}`).join(",")}}`;
  return JSON.stringify(value);
}

// The revision of a flow: the first 8 hex digits of the sha256 of its canonical JSON. It names the
// workflow row a squad runs (template_ref flow_<squad>@<rev>), so a changed flow is a new row.
export const flowRev = (flow) => createHash("sha256").update(canonicalJson(flow)).digest("hex").slice(0, 8);

// The flows by manifest id, as the quickstart and the Go build read them.
export function flowsById(entries) {
  return Object.fromEntries(
    entries
      .filter(isFlowWorkflow)
      .sort((a, b) => (a.manifest.id < b.manifest.id ? -1 : 1))
      .map((e) => [e.manifest.id, { id: e.manifest.id, version: e.manifest.version, rev: flowRev(e.manifest.flow), squad: e.manifest.flow.squad, config: e.manifest.flow.config, steps: e.manifest.flow.steps }]),
  );
}

export function renderFlows(entries) {
  return `${HEADER}import type { CatalogFlow } from "../types";

/** The enforced flows (catalog/workflows/flow_*), by manifest id. */
export const CATALOG_FLOWS: Readonly<Record<string, CatalogFlow>> = ${JSON.stringify(flowsById(entries), null, 2)};
`;
}

// The limits of issueworkflow (flow.go); the Go build checks the same data again with ValidateFlow.
const FLOW_LIMITS = { steps: 12, tasks: 8, switches: 8, titleRunes: 80, instructionRunes: 8000, reworkRounds: 5 };
const FLOW_KEY = /^[a-z][a-z0-9_]{0,31}$/;
const FLOW_FIELDS = ["tasks_outcome", "rework_count", "outcome"];
const FIXED_STATUSES = ["backlog", "todo", "in_progress", "in_review", "blocked", "done", "cancelled"];
const runes = (text) => [...text].length;

function walkConditions(condition, visit) {
  if (!isObject(condition)) return;
  if (Array.isArray(condition.all)) condition.all.forEach((c) => walkConditions(c, visit));
  else if (Array.isArray(condition.any)) condition.any.forEach((c) => walkConditions(c, visit));
  else if (condition.not !== undefined) walkConditions(condition.not, visit);
  else visit(condition);
}

// N of a condition that requires rework_count lt N, alone or inside an `all` group.
function reworkLimit(condition) {
  const own = (c) => (isObject(c) && c.field === "rework_count" && c.op === "lt" && Number.isInteger(c.value) ? c.value : undefined);
  if (!isObject(condition)) return undefined;
  if (Array.isArray(condition.all)) return condition.all.map(own).find((n) => n !== undefined);
  return own(condition);
}

function validateFlowConfig(config, err) {
  if (!isObject(config)) return err("flow.config is required");
  if (config.version !== 1) err("flow.config.version must be 1");
  const switches = config.switches ?? [];
  if (!Array.isArray(switches) || switches.length > FLOW_LIMITS.switches) err(`flow.config.switches must be a list of at most ${FLOW_LIMITS.switches}`);
  const declared = new Map();
  for (const sw of Array.isArray(switches) ? switches : []) {
    if (!isObject(sw) || !FLOW_KEY.test(sw.key ?? "")) { err(`flow switch key ${JSON.stringify(sw?.key)} must match ${FLOW_KEY}`); continue; }
    if (declared.has(sw.key)) err(`flow switch ${sw.key} is declared twice`);
    declared.set(sw.key, sw);
    if (sw.type === "bool") {
      if (typeof sw.default !== "boolean") err(`flow switch ${sw.key}: default must be true or false`);
    } else if (sw.type === "enum") {
      if (!Array.isArray(sw.values) || sw.values.length === 0 || !sw.values.every(isNonEmptyString) || new Set(sw.values).size !== sw.values.length) err(`flow switch ${sw.key}: values must be a list of distinct strings`);
      else if (!sw.values.includes(sw.default)) err(`flow switch ${sw.key}: default must be one of its values`);
    } else err(`flow switch ${sw.key}: type must be bool or enum`);
  }
  for (const [name, text] of Object.entries(config.messages ?? {})) {
    if (!["stop1", "stop2", "stop3", "stalled", "human"].includes(name) || typeof text !== "string") err(`flow.config.messages.${name} must be one of stop1, stop2, stop3, stalled, human with a string`);
  }
  return declared;
}

function validateFlowCondition(condition, declared, at, err) {
  walkConditions(condition, (leaf) => {
    const field = leaf.field;
    if (typeof field !== "string") return err(`${at}: a condition needs a field`);
    if (field.startsWith("switch.")) {
      const key = field.slice("switch.".length);
      const sw = declared.get(key);
      if (!sw) return err(`${at}: switch "${key}" is not declared in flow.config`);
      for (const value of leaf.op === "in" && Array.isArray(leaf.value) ? leaf.value : [leaf.value]) {
        if (sw.type === "bool" && typeof value !== "boolean") err(`${at}: switch "${key}" is a bool: compare it with true or false`);
        if (sw.type === "enum" && !sw.values?.includes(value)) err(`${at}: value ${JSON.stringify(value)} is not one of the values of switch "${key}"`);
      }
    } else if (!FLOW_FIELDS.includes(field)) err(`${at}: field "${field}" is not one a flow condition can read`);
  });
}

// Whether some transition of the step tests field against value.
const routesOn = (step, field, value) => (step.transitions ?? []).some((tr) => {
  let found = false;
  walkConditions(tr.when, (leaf) => { if (leaf.field === field && (leaf.value === value || (Array.isArray(leaf.value) && leaf.value.includes(value)))) found = true; });
  return found;
});

export function validateFlow(entry, problems, context) {
  const err = (message) => problems.errors.push(`${entry.path}: ${message}`);
  const { manifest } = entry;
  const flow = manifest.flow;
  if (manifest.workflow !== undefined || manifest.designer !== undefined) return err("a workflow has either a workflow, a designer or a flow block, not several");
  if (manifest.ui !== false) err("flow workflows set ui to false (their text is the pack's, not a translated card)");
  if (!isObject(flow)) return err("flow block must be an object");
  if (!isNonEmptyString(flow.squad)) return err("flow.squad must name a squad template");
  if (manifest.id !== `flow_${flow.squad}`) err(`id must be "flow_${flow.squad}" (flow_ plus flow.squad)`);
  const first = context.flowSquads.get(flow.squad);
  if (first) err(`squad ${flow.squad} already has a flow in ${first}; keep one`);
  else context.flowSquads.set(flow.squad, entry.path);
  const squadEntry = context.entries.find((e) => e.kind === "squad" && e.manifest?.id === flow.squad);
  if (!squadEntry) err(`flow.squad "${flow.squad}" is not a squad in the catalog`);
  const squad = squadEntry?.manifest?.squad;
  const roleKeys = new Set((squad?.roles ?? []).map((r) => r.key));

  const declared = validateFlowConfig(flow.config, err) ?? new Map();
  if (!Array.isArray(flow.steps) || flow.steps.length === 0) return err("flow.steps must list at least one step");
  if (flow.steps.length > FLOW_LIMITS.steps) err(`a flow can have at most ${FLOW_LIMITS.steps} statuses`);

  const keys = [];
  for (const [index, step] of flow.steps.entries()) {
    const at = `flow step ${index + 1}`;
    if (!isObject(step) || !isObject(step.status)) { err(`${at}: status is required`); keys.push(null); continue; }
    const fromStatus = "key" in step.status ? step.status.key : isNonEmptyString(step.status.name) ? deriveKey(step.status.name) : undefined;
    if (!fromStatus) { err(`${at}: status needs a key or a name`); keys.push(null); continue; }
    if (step.statusKey !== fromStatus) err(`${at}: statusKey "${step.statusKey}" must be "${fromStatus}" (the key of its status)`);
    if (keys.includes(fromStatus)) err(`${at}: status ${fromStatus} is listed twice`);
    keys.push(fromStatus);
  }
  const known = new Set([...keys.filter(Boolean), ...FIXED_STATUSES]);

  const used = new Set();
  let withTasks = 0;
  for (const [index, step] of flow.steps.entries()) {
    const key = keys[index];
    if (!key) continue;
    const at = `flow step ${key}`;
    if (step.humanOnly !== undefined && typeof step.humanOnly !== "boolean") err(`${at}: humanOnly must be true or false`);
    const tasks = step.tasks ?? [];
    if (!Array.isArray(tasks) || tasks.length > FLOW_LIMITS.tasks) { err(`${at}: tasks must be a list of at most ${FLOW_LIMITS.tasks}`); continue; }
    if (tasks.length > 0) withTasks += 1;
    if (key === "todo" && tasks.length > 0) err(`the plan step todo cannot have tasks`);
    const taskKeys = new Set();
    const gateRoles = new Map();
    for (const task of tasks) {
      const ref = `task ${task?.key}`;
      if (!isObject(task) || !FLOW_KEY.test(task.key ?? "")) { err(`${at}: task key ${JSON.stringify(task?.key)} must match ${FLOW_KEY}`); continue; }
      if (taskKeys.has(task.key)) err(`${at}: ${ref} is listed twice`);
      taskKeys.add(task.key);
      if (!isNonEmptyString(task.title) || runes(task.title.trim()) > FLOW_LIMITS.titleRunes) err(`${ref}: title must be 1-${FLOW_LIMITS.titleRunes} characters`);
      if (typeof task.instructions !== "string" || runes(task.instructions) > FLOW_LIMITS.instructionRunes) err(`${ref}: instructions must be a string of at most ${FLOW_LIMITS.instructionRunes} characters`);
      if (!["work", "gate"].includes(task.kind)) err(`${ref}: kind must be work or gate`);
      const requires = task.requires ?? [];
      if (!Array.isArray(requires) || requires.some((r) => !["outcome", "attachment"].includes(r))) err(`${ref}: requires must list outcome or attachment`);
      else if (task.kind === "gate" && !requires.includes("outcome")) err(`gate task ${task.key} must require an outcome`);
      if (!isNonEmptyString(task.role)) err(`${ref}: role must be a role key of the squad`);
      else if (squad) {
        if (!roleKeys.has(task.role)) err(`${ref}: role "${task.role}" is not a role of squad ${flow.squad}`);
        else if (task.role === squad.leader) err(`${ref}: role "${task.role}" is the squad leader; the leader plans and does not take tasks`);
        else used.add(task.role);
      }
      if (task.kind === "gate" && task.role) {
        if (gateRoles.has(task.role)) err(`gates ${gateRoles.get(task.role)} and ${task.key} of step ${key} use the same role`);
        gateRoles.set(task.role, task.key);
      }
      if (task.when !== undefined && task.when !== null) validateFlowCondition(task.when, declared, `${ref}`, err);
    }
    if (index > 0) {
      for (const task of tasks.filter((t) => t?.kind === "gate")) {
        for (const before of flow.steps[index - 1].tasks ?? []) {
          if (before.kind === "work" && before.role === task.role) err(`gate ${task.key} uses the same role as work task ${before.key} of the previous step`);
        }
      }
    }
    if (step.humanOnly) {
      for (const task of tasks) if (task.key !== "export" || !task.when) err(`${at} is human-only: its only agent task is the optional export`);
    }

    const transitions = step.transitions ?? [];
    if (!Array.isArray(transitions)) { err(`${at}: transitions must be a list`); continue; }
    const ids = new Set();
    for (const [j, tr] of transitions.entries()) {
      const tat = `${at} transition ${tr?.id ?? j + 1}`;
      if (!isObject(tr) || !isNonEmptyString(tr.id) || !isNonEmptyString(tr.label)) { err(`${tat}: id and label are required`); continue; }
      if (ids.has(tr.id)) err(`${tat}: id is used twice in the step`);
      ids.add(tr.id);
      if (tr.when !== null && tr.when !== undefined) validateFlowCondition(tr.when, declared, tat, err);
      else if (j !== transitions.length - 1) err(`${tat}: the default transition (when null) must come last`);
      if (!isNonEmptyString(tr.to) || !known.has(tr.to)) err(`${tat}: to "${tr.to}" is not a status of the flow`);
    }
    if (transitions.length > 0 && !transitions.some((tr) => tr?.when === null || tr?.when === undefined)) err(`${at} needs a default transition (when null)`);
    if (tasks.length > 0 && !step.humanOnly) {
      if (transitions.length === 0) err(`${at} has tasks and needs transitions`);
      if (tasks.some((t) => t?.kind === "gate") && !routesOn(step, "tasks_outcome", "all_approved")) err(`step ${key} has gates and needs a transition for tasks_outcome all_approved`);
    }
    if (key === "todo" && !transitions.some((tr) => tr?.when === null || tr?.when === undefined)) err("the plan step todo needs a default transition");
  }
  if (withTasks === 0) err("a flow needs at least one step with tasks");
  if (!keys.includes("todo")) err('a flow needs the "todo" plan step');
  if (squad) for (const role of roleKeys) if (role !== squad.leader && !used.has(role)) err(`role ${role} is never used by a task; give it work or drop it from the squad`);

  // Rework transitions go back to an earlier step with a limit; the rest must not form a cycle.
  const edges = new Map();
  for (const [index, step] of flow.steps.entries()) {
    const from = keys[index];
    for (const tr of Array.isArray(step?.transitions) ? step.transitions : []) {
      if (!isObject(tr) || !from) continue;
      if (!tr.rework) { edges.set(from, [...(edges.get(from) ?? []), tr.to]); continue; }
      const target = keys.indexOf(tr.to);
      if (target < 0 || target >= index) { err(`rework transition ${tr.id} must go back to an earlier step`); continue; }
      const limit = reworkLimit(tr.when);
      if (limit === undefined) err(`rework transition ${tr.id} needs a condition rework_count lt N`);
      else if (limit < 1 || limit > FLOW_LIMITS.reworkRounds) err(`rework transition ${tr.id} can allow at most ${FLOW_LIMITS.reworkRounds} rounds`);
    }
  }
  const state = new Map();
  const cyclic = (node) => {
    if (state.get(node) === 1) return true;
    if (state.get(node) === 2) return false;
    state.set(node, 1);
    for (const next of edges.get(node) ?? []) if (cyclic(next)) return true;
    state.set(node, 2);
    return false;
  };
  if (keys.filter(Boolean).some(cyclic)) err("the transitions of this flow form a cycle without a rework transition");
}

const DESIGNER_CATEGORIES = ["unstarted", "started", "done", "closed"];

function validateDesigner(entry, problems) {
  const err = (message) => problems.errors.push(`${entry.path}: ${message}`);
  const { designer, workflow } = entry.manifest;
  if (workflow !== undefined) return err("a workflow has either a workflow block or a designer block, not both");
  if (!isObject(designer) || !isNonEmptyString(designer.templateId) || !/^[a-z][a-z0-9_]*$/.test(designer.templateId)) return err("designer.templateId must be lower_snake_case");
  if (entry.manifest.id !== `designer_${designer.templateId}`) err(`id must be "designer_${designer.templateId}" (designer_ plus designer.templateId)`);
  if (!Array.isArray(designer.steps) || designer.steps.length === 0) return err("designer.steps must list at least one step");
  const keys = [];
  for (const [index, step] of designer.steps.entries()) {
    const at = `designer step ${index + 1}`;
    const created = step.new !== undefined;
    if (created === (step.statusKey !== undefined)) { err(`${at}: give exactly one of statusKey and new`); keys.push(null); continue; }
    if (created) {
      if (!isObject(step.new) || !isNonEmptyString(step.new.name) || !DESIGNER_CATEGORIES.includes(step.new.category)) { err(`${at}: new needs a name and a category (${DESIGNER_CATEGORIES.join(", ")})`); keys.push(null); continue; }
      keys.push(deriveKey(step.new.name));
    } else {
      if (!isNonEmptyString(step.statusKey)) { err(`${at}: statusKey must be a non-empty string`); keys.push(null); continue; }
      keys.push(step.statusKey);
    }
    if (step.roleHint !== undefined && !isNonEmptyString(step.roleHint)) err(`${at}: roleHint must be a role key`);
    if (step.instructions !== undefined && typeof step.instructions !== "string") err(`${at}: instructions must be a string`);
  }
  const seen = new Set();
  for (const key of keys) {
    if (key && seen.has(key)) err(`status ${key} is listed twice`);
    if (key) seen.add(key);
  }
  for (const [index, step] of designer.steps.entries()) {
    for (const [j, transition] of (step.transitions ?? []).entries()) {
      const at = `designer step ${index + 1} transition ${j + 1}`;
      if (transition.on !== undefined && !["rejected", "blocked"].includes(transition.on)) err(`${at}: on must be "rejected" or "blocked"`);
      if (!isNonEmptyString(transition.to) || !seen.has(transition.to)) err(`${at}: to "${transition.to}" is not a column of the template`);
    }
  }
}

export function validateWorkflow(entry, problems, context) {
  const err = (message) => problems.errors.push(`${entry.path}: ${message}`);
  if (entry.manifest.flow !== undefined) return validateFlow(entry, problems, context);
  if (entry.manifest.designer !== undefined) return validateDesigner(entry, problems);
  const wf = entry.manifest.workflow;
  if (!isObject(wf)) return err("workflow block is missing");
  if (!isNonEmptyString(wf.name) || !isNonEmptyString(wf.description)) err("workflow.name and workflow.description are required");
  if (!Array.isArray(wf.steps) || wf.steps.length === 0) return err("workflow.steps must list at least one step");
  const keys = new Set();
  for (const [index, step] of wf.steps.entries()) {
    const at = `step ${index + 1}`;
    if (!isObject(step) || !isObject(step.status)) { err(`${at}: status is required`); continue; }
    const fromStatus = "key" in step.status ? step.status.key : isNonEmptyString(step.status.name) ? deriveKey(step.status.name) : undefined;
    if (!fromStatus) { err(`${at}: status needs a key or a name`); continue; }
    if (step.statusKey !== fromStatus) err(`${at}: statusKey "${step.statusKey}" must be "${fromStatus}" (the key of its status)`);
    if (keys.has(step.statusKey)) err(`${at}: status ${step.statusKey} is listed twice`);
    keys.add(step.statusKey);
    if (step.role !== null && !isNonEmptyString(step.role)) err(`${at}: role must be a role key or null`);
    if (step.role === null && step.optionalRole) err(`${at}: optionalRole needs a role`);
    if (typeof step.instructions !== "string") err(`${at}: instructions must be a string`);
  }
  // next and back must name a status of this workflow, or one every workflow has.
  const fixed = new Set(["backlog", "todo", "in_progress", "in_review", "blocked", "done", "cancelled"]);
  for (const step of wf.steps) {
    for (const field of ["next", "back"]) {
      if (step[field] !== undefined && !keys.has(step[field]) && !fixed.has(step[field])) err(`step ${step.statusKey}: ${field} "${step[field]}" is not a status of the workflow`);
    }
  }
}
