// Contracts (spec 6.3.4): a template that code depends on by name or id says so with `contracts`.
// The index below is what the Go and TypeScript tests read to prove every contract is still met.
import { isNonEmptyString } from "./validate-shared.mjs";

const HEADER = "// Generated by scripts/catalog/cli.mjs from catalog/. Not committed: run `pnpm catalog:build`.\n";

// A contract id is `<kind>.<name>`; the kind is the kind of template that may provide it.
export const CONTRACT_ID = /^(squad|workflow|company)\.[a-z][a-z0-9_]*$/;

export function validateContracts(entry, problems) {
  for (const id of entry.manifest.contracts ?? []) {
    if (!isNonEmptyString(id)) continue;
    const match = CONTRACT_ID.exec(id);
    if (!match) problems.errors.push(`${entry.path}: contract "${id}" must look like squad.sdlc (squad|workflow|company, a dot, then lower_snake_case)`);
    else if (match[1] !== entry.kind) problems.errors.push(`${entry.path}: contract "${id}" can only be provided by a ${match[1]}, not a ${entry.kind}`);
  }
}

export function contractsIndex(entries) {
  const providers = {};
  const squads = {};
  const workflows = {};
  const sorted = [...entries].sort((a, b) => (a.manifest.id < b.manifest.id ? -1 : 1));
  for (const entry of sorted) {
    const { manifest } = entry;
    if (!manifest.contracts?.length) continue;
    for (const id of manifest.contracts) {
      (providers[id] ??= []).push({ kind: entry.kind, id: manifest.id, status: manifest.status ?? "stable" });
    }
    if (entry.kind === "squad") {
      const roles = {};
      for (const role of manifest.squad.roles) if (role.name) roles[role.key] = role.name;
      squads[manifest.id] = { name: manifest.squad.name, roles };
    } else if (entry.kind === "workflow" && manifest.workflow) {
      workflows[manifest.id] = { name: manifest.workflow.name };
    }
  }
  return { providers: Object.fromEntries(Object.entries(providers).sort(([a], [b]) => (a < b ? -1 : 1))), squads, workflows };
}

export function renderContracts(entries) {
  const { providers } = contractsIndex(entries);
  return `${HEADER}
export interface CatalogContractProvider {
  kind: "squad" | "workflow" | "company";
  id: string;
  status: "stable" | "beta" | "deprecated" | "hidden";
}

/** The templates that provide each contract the code depends on (catalog \`contracts\` field), by contract id. */
export const CATALOG_CONTRACTS: Readonly<Record<string, readonly CatalogContractProvider[]>> = ${JSON.stringify(providers, null, 2)};
`;
}
