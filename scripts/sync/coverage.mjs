#!/usr/bin/env node
// `pnpm sync:coverage`: which upstream files carry substantive fork edits that no
// fork-contract.json check names. Those are the places a "take upstream" resolution
// could drop a fork feature without sync:contract noticing.
//
//   node scripts/sync/coverage.mjs [--min <added lines>] [--limit <n>] [--upstream <ref>]
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { parseArgs } from "node:util";
import { fileURLToPath, pathToFileURL } from "node:url";
import { brandOnly, parseDiff } from "./surface.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const SKIP = [/\/locales\//, /\/generated\//, /^apps\/docs\/content\//, /pnpm-lock\.yaml$/, /\/testdata\//, /\.test\.[a-z]+$/, /_test\.go$/, /\.md$/, /\.mdx$/, /\.json$/, /\.sql$/];

/** Files named by any contract check. */
export function coveredPaths(contract) {
  const out = new Set();
  for (const f of contract.features) for (const c of f.checks) if (c.path) out.add(c.path);
  return out;
}

/** Modified, non-brand-only files with at least `min` added lines that no check names. */
export function uncovered({ files, covered, min = 15 }) {
  return [...files]
    .filter(([f, d]) => !SKIP.some((re) => re.test(f)) && !brandOnly(d) && d.added.length >= min && !covered.has(f))
    .map(([f, d]) => ({ file: f, added: d.added.length, removed: d.removed.length }))
    .sort((a, b) => b.added - a.added);
}

const DECL = [
  /^(?:func (?:\([^)]*\) )?|type |var |const )(\w+)/,
  /^(?:export )?(?:default )?(?:async )?(?:function\*? |const |class |abstract class |type |interface |enum )(\w+)/,
  /^  (?:async )?(?:protected |private |public )?(\w+)\(.*\)(?:: [^{]+)? \{$/,
];
const escape = (t) => t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/\s+/g, "\\s+");

/** Checks that prove the fork's edits in `added` are still in the file: its declarations, else its longest code line. */
export function inlineChecks(file, added) {
  const names = [];
  for (const line of added) {
    for (const re of DECL) {
      const m = re.exec(line);
      if (m && m[1].length >= 5 && !names.includes(m[1])) {
        names.push(m[1]);
        break;
      }
    }
  }
  if (names.length) return names.slice(0, 3).map((n) => ({ kind: "matches", path: file, pattern: `\\b${n}\\b` }));
  const code = added
    .map((l) => l.trim())
    .filter((l) => l.length >= 28 && !/^(\/\/|\/\*|\*|#|import |export \*|<!--)/.test(l))
    .sort((a, b) => b.length - a.length);
  return code.length ? [{ kind: "matches", path: file, pattern: escape(code[0].slice(0, 120)) }] : [];
}

export function main(argv) {
  const { values: v } = parseArgs({ args: argv, options: { min: { type: "string", default: "15" }, limit: { type: "string", default: "80" }, upstream: { type: "string", default: "upstream/main" }, write: { type: "boolean" } } });
  const root = execFileSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim();
  const git = (...a) => execFileSync("git", a, { cwd: root, encoding: "utf8", maxBuffer: 1 << 30 });
  const files = parseDiff(git("diff", "-U0", "--no-renames", "--diff-filter=M", v.upstream, "HEAD"));
  const contract = JSON.parse(readFileSync(join(here, "fork-contract.json"), "utf8"));
  const rows = uncovered({ files, covered: coveredPaths(contract), min: Number(v.min) });
  console.log(`${rows.length} modified upstream files with >= ${v.min} added fork lines are not named by any contract check`);
  for (const r of rows.slice(0, Number(v.limit))) console.log(`${String(r.added).padStart(6)} +  ${String(r.removed).padStart(5)} -  ${r.file}`);
  if (v.write) {
    const features = rows
      .map((r) => ({ id: `inline:${r.file}`, why: "Fork edits inside an upstream file (generated by sync:coverage --write); a failure means a merge dropped them.", checks: inlineChecks(r.file, files.get(r.file).added) }))
      .filter((f) => f.checks.length);
    const doc = { _doc: "Generated by `node scripts/sync/coverage.mjs --write` from a verified-good tree. Regenerate only after a merge you have reviewed, never to silence a failure.", features };
    writeFileSync(join(here, "fork-inline.json"), `${JSON.stringify(doc, null, 1)}\n`);
    console.log(`wrote ${features.length} inline features to scripts/sync/fork-inline.json`);
  }
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) process.exit(main(process.argv.slice(2)));
